"""Write video/hidden/film_data.js: the decision robots' registered measures, straight from their hidden.json files, for
the film's charts (so no number is retyped).
  python3 video/hidden/make_film_data.py
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, '..', '..', 'out', 'hidden', 'runs')
NOW = ['linear_now', 'mlp_now', 'mlpbig_now']
OTHER = ['mlp_memory', 'mlpbig_memory', 'linear_both', 'mlp_both', 'mlpbig_both']
rows = []
for arm in ('control', 'hidden'):
    for s in range(51, 56):
        x = json.load(open(os.path.join(R, f'{arm}-{s}', 'hidden.json')))
        q = x['probes_probation']
        now = max(q[k]['acc'] for k in NOW)
        t = x['transplant']
        rows.append(dict(run=f'{arm}-{s}', arm=arm, turns=x['turns'],
                         reads_linear=round(q['linear_memory']['acc'] - now, 4),
                         reads_strongest=round(max(q[k]['acc'] for k in OTHER) - now, 4),
                         photos_probation=round(x['behaviour']['photos_probation'], 4),
                         photos_trusted=round(x['behaviour']['photos_trusted'], 4),
                         raise_by_count=[None if v is None else round(v, 4) for v in x['raise_by_count']],
                         use=round(t['trusted_memory']['photos_probation'] - t['own_count']['photos_probation'], 4)))
open(os.path.join(HERE, 'film_data.js'), 'w').write('// generated by make_film_data.py from out/hidden/runs/*/hidden.json - do not edit\nexport const ROBOTS = '
                                                     + json.dumps(rows, indent=1) + ';\n')
print(len(rows), 'robots written')
for r in rows:
    print(r['run'], r['turns'], r['reads_linear'], r['reads_strongest'], r['photos_probation'], r['use'])
